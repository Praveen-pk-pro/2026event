if (typeof window !== 'undefined') {
  Object.entries(LOGO_PATHS).forEach(([id, src]) => {
    try {
      const img = new Image();
      img.src = src;
      img.onload = () => {
        BRAND_IMAGES[id] = img;
      };
    } catch (e) {
      // Ignored
    }
  });
}

/**
 * Draws high-precision vector emblem and holographic reticle for any AI Target
 */
export function drawAIEmblem(ctx, ai, cx, cy, size, pulse = 0) {
  ctx.save();
  ctx.translate(cx, cy);

  const radius = size / 2;
  const pulseScale = 1.0 + Math.sin(pulse) * 0.06;
  ctx.scale(pulseScale, pulseScale);

  // 1. Holographic Outer Rotating Brackets
  ctx.save();
  ctx.rotate(pulse * 0.4);
  ctx.strokeStyle = ai.color;
  ctx.lineWidth = 2.5;
  ctx.shadowColor = ai.glow;
  ctx.shadowBlur = 18;

  // Quad segmented brackets
  for (let i = 0; i < 4; i++) {
    ctx.beginPath();
    ctx.arc(0, 0, radius + 12, i * Math.PI * 0.5 + 0.18, (i + 1) * Math.PI * 0.5 - 0.18);
    ctx.stroke();
  }
  ctx.restore();

  // 2. Counter-rotating inner reticle
  ctx.save();
  ctx.rotate(-pulse * 0.6);
  ctx.strokeStyle = 'rgba(255, 255, 255, 0.4)';
  ctx.lineWidth = 1.5;
  ctx.setLineDash([6, 6]);
  ctx.beginPath();
  ctx.arc(0, 0, radius + 4, 0, Math.PI * 2);
  ctx.stroke();
  ctx.setLineDash([]);
  ctx.restore();

  // 3. Holographic Shield Glow Disc
  const grad = ctx.createRadialGradient(0, 0, radius * 0.2, 0, 0, radius + 8);
  grad.addColorStop(0, 'rgba(15, 23, 42, 0.95)');
  grad.addColorStop(0.7, 'rgba(15, 23, 42, 0.85)');
  grad.addColorStop(1, `${ai.color}44`);
  ctx.fillStyle = grad;
  ctx.beginPath();
  ctx.arc(0, 0, radius, 0, Math.PI * 2);
  ctx.fill();

  ctx.strokeStyle = ai.color;
  ctx.lineWidth = 3;
  ctx.stroke();

  // 4. Render Brand Logo Image if available, or Vector Icon Art
  const brandImg = BRAND_IMAGES[ai.id];
  if (brandImg && brandImg.complete && brandImg.naturalWidth > 0) {
    ctx.save();
    ctx.beginPath();
    ctx.arc(0, 0, radius * 0.74, 0, Math.PI * 2);
    ctx.clip();
    const imgSize = radius * 1.48;
    ctx.drawImage(brandImg, -imgSize / 2, -imgSize / 2, imgSize, imgSize);
    ctx.restore();
  } else {
    ctx.save();
    ctx.fillStyle = ai.color;
    ctx.strokeStyle = ai.color;
    ctx.lineWidth = 2.8;
    ctx.shadowColor = ai.glow;
    ctx.shadowBlur = 14;

    const s = radius * 0.55;

    switch (ai.id) {
      case 'chatgpt': {
        // Iconic OpenAI Pinwheel Swirl
        for (let i = 0; i < 6; i++) {
          ctx.save();
          ctx.rotate((i * Math.PI) / 3);
          ctx.beginPath();
          ctx.arc(s * 0.35, 0, s * 0.45, 0, Math.PI * 1.3);
          ctx.stroke();
          ctx.restore();
        }
        break;
      }

    case 'gemini': {
      // 4-Point Gemini Sparkle Star
      ctx.beginPath();
      ctx.moveTo(0, -s);
      ctx.quadraticCurveTo(0, 0, s, 0);
      ctx.quadraticCurveTo(0, 0, 0, s);
      ctx.quadraticCurveTo(0, 0, -s, 0);
      ctx.quadraticCurveTo(0, 0, 0, -s);
      ctx.closePath();
      ctx.fill();
      ctx.stroke();
      break;
    }

    case 'claude': {
      // Anthropic Asterisk / Spark
      for (let i = 0; i < 8; i++) {
        ctx.save();
        ctx.rotate((i * Math.PI) / 4);
        ctx.fillRect(-s * 0.12, -s * 0.9, s * 0.24, s * 0.6);
        ctx.restore();
      }
      ctx.beginPath();
      ctx.arc(0, 0, s * 0.35, 0, Math.PI * 2);
      ctx.fill();
      break;
    }

    case 'deepseek': {
      // DeepSeek Whale Fin / Cyber Swoosh
      ctx.beginPath();
      ctx.moveTo(-s * 0.7, -s * 0.2);
      ctx.bezierCurveTo(-s * 0.3, -s * 0.9, s * 0.5, -s * 0.7, s * 0.8, -s * 0.1);
      ctx.bezierCurveTo(s * 0.4, s * 0.6, -s * 0.1, s * 0.7, -s * 0.6, s * 0.4);
      ctx.closePath();
      ctx.fill();
      // Eye
      ctx.fillStyle = '#0f172a';
      ctx.beginPath();
      ctx.arc(-s * 0.2, -s * 0.2, s * 0.12, 0, Math.PI * 2);
      ctx.fill();
      break;
    }

    case 'grok': {
      // xAI Grok Slash / X
      ctx.lineWidth = 4.5;
      ctx.beginPath();
      ctx.moveTo(-s * 0.7, -s * 0.7);
      ctx.lineTo(s * 0.7, s * 0.7);
      ctx.moveTo(s * 0.6, -s * 0.7);
      ctx.lineTo(-s * 0.6, s * 0.7);
      ctx.stroke();
      break;
    }

    case 'copilot': {
      // Microsoft Copilot Loop
      ctx.lineWidth = 4;
      ctx.beginPath();
      ctx.arc(-s * 0.25, 0, s * 0.45, Math.PI * 0.5, Math.PI * 1.5);
      ctx.arc(s * 0.25, 0, s * 0.45, -Math.PI * 0.5, Math.PI * 0.5);
      ctx.closePath();
      ctx.stroke();
      break;
    }

    case 'perplexity': {
      // Perplexity Intersecting Compass Lines
      ctx.lineWidth = 3.5;
      ctx.strokeRect(-s * 0.5, -s * 0.5, s, s);
      ctx.beginPath();
      ctx.moveTo(-s * 0.7, 0); ctx.lineTo(s * 0.7, 0);
      ctx.moveTo(0, -s * 0.7); ctx.lineTo(0, s * 0.7);
      ctx.stroke();
      break;
    }

    case 'cursor': {
      // Isometric 3D Cursor Box
      ctx.lineWidth = 3;
      ctx.beginPath();
      ctx.moveTo(0, -s * 0.8);
      ctx.lineTo(s * 0.7, -s * 0.4);
      ctx.lineTo(s * 0.7, s * 0.4);
      ctx.lineTo(0, s * 0.8);
      ctx.lineTo(-s * 0.7, s * 0.4);
      ctx.lineTo(-s * 0.7, -s * 0.4);
      ctx.closePath();
      ctx.stroke();
      ctx.beginPath();
      ctx.moveTo(0, -s * 0.8); ctx.lineTo(0, s * 0.8);
      ctx.stroke();
      break;
    }

    case 'sora': {
      // Sora Cinematic Aperture
      ctx.lineWidth = 3;
      ctx.beginPath();
      ctx.arc(0, 0, s * 0.75, 0, Math.PI * 2);
      ctx.stroke();
      for (let i = 0; i < 6; i++) {
        ctx.save();
        ctx.rotate((i * Math.PI) / 3);
        ctx.beginPath();
        ctx.moveTo(s * 0.35, 0);
        ctx.lineTo(s * 0.75, -s * 0.3);
        ctx.stroke();
        ctx.restore();
      }
      break;
    }

    default: {
      // Futuristic AI Target Hex-Core with Monogram
      ctx.lineWidth = 3.5;
      ctx.beginPath();
      for (let i = 0; i < 6; i++) {
        const angle = (i * Math.PI) / 3;
        const hx = Math.cos(angle) * s * 0.85;
        const hy = Math.sin(angle) * s * 0.85;
        if (i === 0) ctx.moveTo(hx, hy);
        else ctx.lineTo(hx, hy);
      }
      ctx.closePath();
      ctx.stroke();

      ctx.fillStyle = '#ffffff';
      ctx.font = `bold ${Math.round(s * 0.75)}px "Rajdhani", sans-serif`;
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.fillText(ai.name.charAt(0), 0, 2);
      break;
    }
  }

  ctx.restore();
}

  // 5. Tactical Name Badge Below Target
  ctx.save();
  ctx.font = 'bold 11px "JetBrains Mono", monospace';
  ctx.textAlign = 'center';
  ctx.fillStyle = '#ffffff';
  ctx.shadowColor = '#000000';
  ctx.shadowBlur = 4;
  ctx.fillText(ai.name.toUpperCase(), 0, radius + 28);

  ctx.font = '9px "JetBrains Mono", monospace';
  ctx.fillStyle = ai.color;
  ctx.fillText(`${ai.org.toUpperCase()} • +${ai.points} PTS`, 0, radius + 40);
  ctx.restore();

  ctx.restore();
}
